const EXTRA_COLORS = ['#F28FB0', '#7CC47F', '#E8A33D', '#B79CED', '#4FC3B5', '#F08A5D', '#D4C24A', '#E57373', '#81C784', '#BA68C8',
  '#FFB74D', '#F06292', '#AED581', '#9575CD', '#FF8A65', '#A1887F', '#C0CA33', '#26A69A', '#EC407A', '#8D6E63'];
(function buildCourses() {
  const names = Object.keys(COUNTRIES).filter(n => !COUNTRY_COURSE[n]);
  const perLang = {};
  Object.values(COURSES).forEach(c => { perLang[c.lang] = (perLang[c.lang] || 0) + 1; });
  names.forEach(n => { const k = COUNTRIES[n][1], l = LANGUAGES[k].name || k; perLang[l] = (perLang[l] || 0) + 1; });
  let nextColor = 0;
  names.forEach(n => {
    const [iso, key, icons, opt = {}] = COUNTRIES[n];
    const L = LANGUAGES[key], lang = L.name || key, pretty = COUNTRY_LABEL[n] || n;
    const pm = L.pm || ['hello', 'thank you', 'yes', 'no'], many = perLang[lang] > 1;
    const id = 'x-' + (iso || n.replace(/\W/g, '').toLowerCase());
    const extras = (opt.x || []).map(r => [r[0], r[1], r[2] || ''])
      .concat(L.p.map((t, i) => [t, pm[i], ['👋', '🙏', '✅', '❌'][i]]).filter(r => r[0]));
    if (!LANG_COLORS[lang]) LANG_COLORS[lang] = EXTRA_COLORS[nextColor++ % EXTRA_COLORS.length];
    COURSES[id] = {
      id, lang, dialect: opt.d || (many ? `${lang} (${pretty})` : lang), country: n, flag: flagOf(iso), color: LANG_COLORS[lang],
      tip: (L.tip ? L.tip + ' ' : '') + (many && !L.tip ? `${lang} can sound and look different in each country. ` : '') + 'These starter words were written quickly, so please check them with your teacher.',
      concepts: L.t, meanings: L.m, extras, stickers: icons.split(' ').map(e => [e, ICON_NAMES[e] || 'Icon'])
    };
    COUNTRY_COURSE[n] = id;
  });
})();
